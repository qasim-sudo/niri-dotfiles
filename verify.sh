#!/usr/bin/env bash
# verify.sh — check the desktop against the shipped configuration.
#
#   ./verify.sh              run every check
#   ./verify.sh --quiet      only report failures
#   ./verify.sh --fix        repair what can be repaired safely
#
# This is the same set of checks install.sh runs at the end, split out so you
# can re-run them at any time without reinstalling. It is also what you should
# run if a theme upgrade reverts something, or if a keybinding suddenly stops
# working.
#
# It is READ-ONLY unless you pass --fix. Nothing is installed or removed.

set -uo pipefail

DOTFILES_ROOT="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
export DOTFILES_ROOT

. "$DOTFILES_ROOT/lib/common.sh"
. "$DOTFILES_ROOT/lib/detect.sh"
. "$DOTFILES_ROOT/lib/noctalia.sh"
. "$DOTFILES_ROOT/lib/sddm.sh"
. "$DOTFILES_ROOT/lib/backup.sh"

DRY_RUN=0
FORCE=0
QUIET=0
FIX=0

usage() {
    cat <<'VERIFY_USAGE'
verify.sh — check the desktop against the shipped configuration

USAGE
    ./verify.sh [--quiet] [--fix]

OPTIONS
    --quiet     Report only failures and warnings.
    --fix       Repair what can be repaired without reinstalling:
                  * re-apply the SDDM KEN theme patch
                  * regenerate the per-host niri output.kdl
                  * regenerate the Noctalia runtime overlay
    --dry-run   With --fix, show the repair without performing it.
    -h, --help  This text.

Exit status is the number of failed checks, capped at 125, so it is usable in
a script.
VERIFY_USAGE
    exit "${1:-0}"
}

while [ $# -gt 0 ]; do
    case "$1" in
        -h|--help)  usage 0 ;;
        --quiet)    QUIET=1 ;;
        --fix)      FIX=1 ;;
        --dry-run)  DRY_RUN=1 ;;
        *) err "unknown option: $1"; printf '\n'; usage 1 ;;
    esac
    shift
done

_log_init
banner "verify"
load_local_conf
detect_all

PASS=0
FAIL=0

# ---------------------------------------------------------------------------
check() {
    # check <description> <command...>
    local desc="$1"; shift
    if "$@" >/dev/null 2>&1; then
        PASS=$((PASS + 1))
        [ "$QUIET" = 1 ] || ok "$desc"
        return 0
    fi
    FAIL=$((FAIL + 1))
    warn "$desc"
    return 1
}

# ---------------------------------------------------------------------------
step "Packages the keybindings and the desktop shell invoke"
# Each of these is the target of a shipped keybinding, or a component of the
# shell. If one is missing, something on screen is about to stop working.
for p in niri noctalia kitty fish starship fastfetch fuzzel thunar swaylock \
         playerctl brightnessctl ffmpeg wireplumber xdg-desktop-portal; do
    desc="$p installed"
    if ! check "$desc" pacman -Qq "$p"; then
        note "a shipped keybinding or panel element will fail without it"
        note "  fix: sudo pacman -S --needed $p"
    elif ! explicit_pkg "$p"; then
        # Present, but only as somebody else's dependency. That is fragile: an
        # unrelated upgrade can remove it and silently break a keybinding.
        warn "$p is only a dependency of something else, not explicitly installed"
        note "  fix: sudo pacman -S --needed $p"
        note "  an unrelated package upgrade can remove it and break a keybinding"
    fi
done

# ---------------------------------------------------------------------------
step "Packages the shipped theme names"
# Each name below is a literal string in a file this repository deploys.
check "font: Adwaita Sans (noctalia [shell] font_family)" \
      bash -c '[ "$(fc-match -f "%{family[0]}" "Adwaita Sans" 2>/dev/null)" = "Adwaita Sans" ]'
check "font: JetBrainsMono Nerd Font Mono (kitty font_family)" \
      bash -c '[ "$(fc-match -f "%{family[0]}" "JetBrainsMono Nerd Font Mono" 2>/dev/null)" = "JetBrainsMono Nerd Font Mono" ]'
check "cursor: Bibata-Modern-Classic (niri XCURSOR_THEME, sddm CursorTheme)" \
      bash -c '[ "$(fc-match -f "%{family[0]}" "Bibata-Modern-Classic" 2>/dev/null)" = "Bibata-Modern-Classic" ]'
check "icons: Papirus-Dark (gtk settings)"  test -d /usr/share/icons/Papirus-Dark
check "gtk theme: adw-gtk3-dark (gtk settings)" test -d /usr/share/themes/adw-gtk3-dark

# ---------------------------------------------------------------------------
step "Configuration files"
check "niri config present"  test -f "$HOME/.config/niri/config.kdl"
# `test -f` alone is not enough: the repository ships a comment-only placeholder
# for output.kdl, so the file can exist and still not have been generated.
if grep -q 'GENERATED by the dotfiles installer' "$HOME/.config/niri/cfg/output.kdl" 2>/dev/null; then
    PASS=$((PASS + 1))
    [ "$QUIET" = 1 ] || ok "niri output.kdl generated for this machine"
else
    FAIL=$((FAIL + 1))
    warn "niri output.kdl is the un-generated placeholder (or missing)"
    note "  niri will auto-detect displays, which is fine, but your modes,"
    note "  scale and positions are not pinned. fix: ./regenerate.sh"
fi
check "noctalia config present" test -f "$HOME/.config/noctalia/config.toml"
check "noctalia runtime overlay present" test -f "$HOME/.local/state/noctalia/settings.toml"
check "kitty config present"  test -f "$HOME/.config/kitty/kitty.conf"
check "fuzzel config present"  test -f "$HOME/.config/fuzzel/fuzzel.ini"
check "starship config present" test -f "$HOME/.config/starship/end4diagonal.toml"
check "fish config present"    test -f "$HOME/.config/fish/config.fish"
check "fastfetch config present" test -f "$HOME/.config/fastfetch/config.jsonc"

if [ ! -f "$HOME/.config/niri/cfg/output.kdl" ]; then
    note "fix: ./regenerate.sh   (needs a running niri session for exact modes)"
fi

# ---------------------------------------------------------------------------
step "Config validity"
if command -v niri >/dev/null 2>&1; then
    if [ "$DETECT_NIRI_RUNNING" = 1 ]; then
        check "niri validate" niri validate
    else
        check "niri validate (offline, no live session)" \
              niri validate -c "$HOME/.config/niri/config.kdl"
    fi
fi

if command -v noctalia >/dev/null 2>&1; then
    out="$(noctalia config validate 2>&1)"
    if printf '%s' "$out" | grep -q '✓ Config is valid'; then
        # The same split the installer uses, via the same helper. Counting
        # plugin-pending warnings as failures here made verify.sh report a
        # perfectly healthy desktop as broken until the first login, while
        # install.sh reported the identical warnings as fine.
        real_w="$(noctalia_split_warnings "$out" real)"
        pend_w="$(noctalia_split_warnings "$out" pending)"
        n_real="$(printf '%s' "$real_w" | grep -c . || true)"
        n_pend="$(printf '%s' "$pend_w" | grep -c . || true)"

        if [ "$n_real" -gt 0 ]; then
            FAIL=$((FAIL + 1))
            warn "noctalia config validate: $n_real real warning(s)"
            printf '%s\n' "$real_w" | sed 's/^/        /'
        else
            PASS=$((PASS + 1))
            if [ "$n_pend" -gt 0 ]; then
                [ "$QUIET" = 1 ] || ok "noctalia config validate: no config warnings ($n_pend plugin widget(s) pending first login)"
            else
                [ "$QUIET" = 1 ] || ok "noctalia config validate: 0 warnings"
            fi
        fi
        [ "$QUIET" = 1 ] || [ "$n_pend" -eq 0 ] || note "plugin widgets are cloned by Noctalia on first login; re-run ./verify.sh afterwards"
    else
        FAIL=$((FAIL + 1))
        warn "noctalia config validate FAILED"
        printf '%s\n' "$out" | sed 's/^/        /'
    fi
fi

# ---------------------------------------------------------------------------
step "Keybinding inventory"
# The shipped binds.kdl must not contain a binding whose target this repository
# does not install. Checked by scanning for the commands the bindings spawn and
# confirming each is either a package or a shell builtin.
binds="$HOME/.config/niri/cfg/binds.kdl"
if [ -f "$binds" ]; then
    n_active="$(grep -vE '^\s*(//|/\*|\*|$)' "$binds" | grep -c '{' || true)"
    ok "$n_active active keybinding(s)"
    if grep -vE '^\s*(//|/\*|\*|$)' "$binds" \
       | grep -oE 'spawn(-sh)? "[^"]+"' | sed -E 's/.*"([^"]+)"/\1/' \
       | awk '{print $1}' | sort -u \
       | while read -r cmd; do
        case "$cmd" in
            *@*) continue ;;               # wpctl target, not a command
        esac
        if ! command -v "$cmd" >/dev/null 2>&1; then
            :
        fi
    done; then :; fi
    # Report any spawn target that is not on PATH.
    missing="$(grep -vE '^\s*(//|/\*|\*|$)' "$binds" \
        | grep -oE 'spawn(-sh)? "[^"]+"' | sed -E 's/.*"([^"]+)"/\1/' \
        | awk '{print $1}' | sort -u \
        | while read -r cmd; do
              case "$cmd" in *@*) continue ;; esac
              command -v "$cmd" >/dev/null 2>&1 || echo "$cmd"
          done)"
    if [ -n "$missing" ]; then
        for m in $missing; do
            FAIL=$((FAIL + 1))
            warn "a keybinding spawns '$m', which is not installed"
            note "  fix: sudo pacman -S --needed $m"
        done
    else
        PASS=$((PASS + 1))
        [ "$QUIET" = 1 ] || ok "every command a keybinding spawns is present"
    fi
fi

# ---------------------------------------------------------------------------
step "Conflicting services must be disabled"
# dms/quickshell/dunst would fight Noctalia for org.freedesktop.Notifications.
# hypridle and cliphist would fight Noctalia for idle handling and the
# clipboard. A second notification daemon on the same bus is the single most
# common cause of "notifications stopped appearing" in this setup.
for u in dms.service dunst.service quickshell.service hypridle.service cliphist.service; do
    systemctl --user list-unit-files "$u" 2>/dev/null | grep -q "^$u" || continue
    # unit_state() (lib/common.sh) exists because the obvious one-liner here is
    # wrong: `is-enabled` prints "disabled" on stdout AND exits non-zero for a
    # disabled unit, so `|| echo unknown` produced the two-line value
    # "disabled\nunknown", which matched no case. The catch-all arm then
    # reported a correctly disabled unit as one that "will fight Noctalia" —
    # on every properly configured machine, inverting the most important check
    # in this file.
    st="$(unit_state "$u" user)"
    case "$st" in
        disabled|masked|static|not-found)
            PASS=$((PASS + 1)); [ "$QUIET" = 1 ] || ok "$u is $st" ;;
        unknown)
            # No answer available — usually no user session (a container, an ssh
            # login, a test harness). That is not evidence of a conflict, and
            # failing on it would report a healthy machine as broken for the
            # sake of a missing session bus. Say what is actually known.
            PASS=$((PASS + 1))
            [ "$QUIET" = 1 ] || note "$u: enablement could not be determined (no user session?); not counted as a conflict"
            ;;
        *)
            FAIL=$((FAIL + 1))
            warn "$u is $st — it will fight Noctalia"
            note "  fix: systemctl --user disable --now $u && systemctl --user mask $u"
            if [ "$FIX" = 1 ]; then
                if [ "$DRY_RUN" = 1 ]; then
                    dry "systemctl --user disable --now $u; systemctl --user mask $u"
                else
                    systemctl --user disable --now "$u" >/dev/null 2>&1
                    systemctl --user mask "$u" >/dev/null 2>&1 \
                        && ok "masked $u" || warn "could not mask $u"
                fi
            fi
            ;;
    esac
done

# ---------------------------------------------------------------------------
step "niri.service must be static"
# niri.service is started by SDDM through niri-session. Enabling or disabling
# it breaks the login session entirely. It must be left alone.
nst="$(unit_state niri.service system)"
case "$nst" in
    static) PASS=$((PASS + 1)); [ "$QUIET" = 1 ] || ok "niri.service is static (correct)" ;;
    disabled|enabled|linked|enabled-runtime)
        FAIL=$((FAIL + 1))
        warn "niri.service is $nst, not static"
        note "  this breaks login. It is started by niri-session via SDDM."
        note "  do not enable or disable it."
        ;;
    *) note "niri.service not found, or its state could not be read ($nst)" ;;
esac

# ---------------------------------------------------------------------------
step "Display manager"
if systemctl list-unit-files sddm.service >/dev/null 2>&1 \
   && systemctl list-unit-files sddm.service 2>/dev/null | grep -q '^sddm.service'; then
    sst="$(unit_state sddm.service system)"
    if [ "$sst" = "enabled" ]; then
        PASS=$((PASS + 1)); [ "$QUIET" = 1 ] || ok "sddm.service enabled"
    else
        warn "sddm.service is $sst"
        note "  if you want the SilentSDDM KEN greeter: sudo systemctl enable sddm"
    fi
fi
# The theme patch is the fragile part: any sddm-silent-theme upgrade reverts it.
if [ "$FIX" = 1 ]; then
    if ! sddm_verify >/dev/null 2>&1; then
        sddm_patch_theme || warn "could not re-apply the SDDM theme patch"
    fi
fi
sddm_verify || true

# ---------------------------------------------------------------------------
step "Default file manager"
if command -v xdg-mime >/dev/null 2>&1 && [ -f /usr/share/applications/thunar.desktop ]; then
    for m in inode/directory application/zip x-scheme-handler/sftp; do
        got="$(xdg-mime query default "$m" 2>/dev/null)"
        if [ "$got" = "thunar.desktop" ]; then
            PASS=$((PASS + 1)); [ "$QUIET" = 1 ] || ok "$m -> thunar.desktop"
        else
            FAIL=$((FAIL + 1))
            warn "$m resolves to '${got:-nothing}', expected thunar.desktop"
            note "  fix: xdg-mime default thunar.desktop $m"
        fi
    done
fi

# ---------------------------------------------------------------------------
step "Portals"
# packages/core.txt installs exactly one backend. A second one registering for
# the niri session is the usual cause of a broken file chooser or screenshot.
if command -v systemctl >/dev/null 2>&1; then
    running="$(systemctl --user list-units --no-legend --plain 'xdg-desktop-portal*' 2>/dev/null \
        | awk '{print $1}' | grep -E '\.service$' | sort -u)"
    nport="$(printf '%s\n' "$running" | grep -c 'xdg-desktop-portal' || true)"
    backends="$(printf '%s\n' "$running" | grep -cE 'portal-(gnome|gtk|wlr)' || true)"
    if [ "$nport" = 0 ]; then
        note "no portal running (normal outside a graphical session)"
    elif [ "$backends" -le 1 ]; then
        PASS=$((PASS + 1)); [ "$QUIET" = 1 ] || ok "exactly one portal backend active"
    else
        FAIL=$((FAIL + 1))
        warn "$backends portal backends are active; that is ambiguous"
        printf '%s\n' "$running" | sed 's/^/        /'
        note "  see ~/.config/xdg-portal/portals.conf"
    fi
fi

# ---------------------------------------------------------------------------
step "No personal data in the repository or the deployed config"
# Two different questions. First: does the SOURCE still leak anything? That
# would be a portability bug. Second: did anything get deployed with a hard
# coded path instead of a @TOKEN@?
if leak_check "repository sources" "${LEAK_SCAN_PATHS[@]}" >/dev/null 2>&1; then
    PASS=$((PASS + 1))
    [ "$QUIET" = 1 ] || ok "repository sources carry no account, hostname, interface or credential"
else
    FAIL=$((FAIL + 1))
    leak_check "repository sources" "${LEAK_SCAN_PATHS[@]}" || true
fi

leaks="$(grep -rIlE '/home/[A-Za-z0-9._-]+' \
            "$HOME/.config/niri" "$HOME/.config/noctalia" \
            "$HOME/.config/fish" "$HOME/.config/kitty" "$HOME/.config/fuzzel" \
            "$HOME/.config/starship" "$HOME/.config/fastfetch" 2>/dev/null || true)"
if [ -n "$leaks" ]; then
    FAIL=$((FAIL + 1))
    warn "a deployed config file contains a hard-coded /home/<someone> path"
    printf '%s\n' "$leaks" | sed 's/^/        /'
    note "  these should have been a @TOKEN@ placeholder"
else
    PASS=$((PASS + 1))
    [ "$QUIET" = 1 ] || ok "no hard-coded home paths in the deployed config"
fi

# fish_variables records absolute paths and is never deployed.
if [ -f "$HOME/.config/fish/fish_variables" ]; then
    note "fish_variables exists (machine-generated by fish itself, never deployed)"
fi

# ---------------------------------------------------------------------------
step "Generated files are current"
if [ "$FIX" = 1 ]; then
    if [ "$DRY_RUN" = 1 ]; then
        dry "regenerate output.kdl + noctalia settings.toml"
    else
        hardware_generate_output 2>/dev/null || true
        noctalia_generate_settings 2>/dev/null || true
    fi
fi

# ---------------------------------------------------------------------------
step "Backups"
n_snap="$(backup_list | wc -l)"
if [ "$n_snap" -gt 0 ]; then
    ok "$n_snap snapshot(s) in ${BACKUP_ROOT/#$HOME/\$HOME}"
    [ "$QUIET" = 1 ] || note "restore one with: ./restore.sh --latest"
else
    note "no snapshots yet (this is normal before the first install)"
fi

# ---------------------------------------------------------------------------
printf '\n'
step "Result"
printf '    passed : %s\n' "$PASS"
printf '    failed : %s\n' "$FAIL"
printf '\n'

if [ "$FAIL" -gt 0 ]; then
    err "$FAIL check(s) failed. Each one above says exactly how to fix it."
    exit "$(( FAIL > 125 ? 125 : FAIL ))"
fi
ok "everything checks out"
exit 0
