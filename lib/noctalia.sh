#!/usr/bin/env bash
# lib/noctalia.sh — generate the per-host parts of the Noctalia configuration.
#
# Two things cannot be committed because they describe the hardware attached
# right now:
#
#   [wallpaper.monitors.<output>]   which display shows which wallpaper
#   [lockscreen_widgets]            one login box per display, positioned in
#                                   that display's own pixel space
#
# Both are written to ~/.local/state/noctalia/settings.toml, the runtime
# overlay Noctalia merges on top of config.toml. The base config.toml in this
# repository contains NO monitor name, NO resolution and NO pixel coordinate.
#
# When no niri session is live (fresh install, running from a TTY), a single
# output-less login box is emitted and Noctalia places it on whichever display
# is actually present. That is the correct portable fallback.

[ -n "${DOTFILES_NOCTALIA_SH:-}" ] && return 0
DOTFILES_NOCTALIA_SH=1

# The one wallpaper this repository ships.
NOCTALIA_WALLPAPER="wallhaven-w5xokr_1920x1080.png"

# ---------------------------------------------------------------------------
# nocturne_generate_settings — write the runtime overlay.
# ---------------------------------------------------------------------------
noctalia_generate_settings() {
    local dest="$HOME/.local/state/noctalia/settings.toml"
    local wall="$WALLPAPER_DIR/$NOCTALIA_WALLPAPER"
    local tmp; tmp="$(mktemp)"

    {
        printf '# GENERATED by the dotfiles installer. DO NOT EDIT, DO NOT COMMIT.\n'
        printf '#\n'
        printf '# Runtime overlay merged on top of ~/.config/noctalia/config.toml.\n'
        printf '# Everything in here is a property of the displays attached when the\n'
        printf '# installer ran. Regenerate at any time with:\n'
        printf '#     ./regenerate.sh   (in the dotfiles repo)\n'
        printf '\n'
        printf 'config_version = 14\n'
        printf '\n'

        if [ "$DETECT_NIRI_RUNNING" = 1 ] && [ -n "$DETECT_OUTPUTS" ]; then
            # ---------------- per-output wallpaper assignment ----------------
            for out in $DETECT_OUTPUTS; do
                printf '[wallpaper.monitors.%s]\n' "$out"
                printf 'path = "%s"\n' "$wall"
                printf '\n'
            done

            # ---------------- one login box per display --------------------
            printf '[lockscreen_widgets]\n'
            printf 'enabled = true\n'
            printf 'schema_version = 2\n'
            printf 'widget_order = [\n'
            local first=1
            for out in $DETECT_OUTPUTS; do
                [ "$first" = 1 ] || printf ',\n'
                printf '    "lockscreen-login-box@%s"' "$out"
                first=0
            done
            printf '\n]\n\n'
            printf '    [lockscreen_widgets.grid]\n'
            printf '    cell_size = 16\n'
            printf '    major_interval = 4\n'
            printf '    visible = true\n\n'

            for out in $DETECT_OUTPUTS; do
                local geom w h px py
                # Box proportions follow Noctalia's 16-column grid: 9 of 16
                # columns wide, so a narrow box on a wide display.
                local box_w=0 box_h=196
                geom="$(output_geometry "$out" || true)"
                if [ -n "$geom" ]; then
                    read -r w h px py <<<"$geom"
                    box_w=$(( w * 9 / 16 ))
                else
                    w=1920; h=1080; px=0; py=0
                    box_w=1080
                fi
                # Centre horizontally, and centre vertically. A login box is the
                # only thing on the lock screen, so centring it is both correct
                # and resolution-independent — the previous "bottom minus 182px"
                # placement put it visibly off-centre on any display taller than
                # 1080, which is most modern panels.
                local cx=$(( px + w / 2 ))
                local cy=$(( py + h / 2 ))
                printf '    [lockscreen_widgets.widget."lockscreen-login-box@%s"]\n' "$out"
                printf '    box_height = %s.0\n' "$box_h"
                printf '    box_width = %s.0\n' "$box_w"
                printf '    cx = %s.0\n' "$cx"
                printf '    cy = %s.0\n' "$cy"
                printf '    output = "%s"\n' "$out"
                printf '    placement_height = %s.0\n' "$h"
                printf '    placement_width = %s.0\n' "$w"
                printf '    rotation = 0.0\n'
                printf '    type = "login_box"\n\n'
                printf '        [lockscreen_widgets.widget."lockscreen-login-box@%s".settings]\n' "$out"
                printf '        background_color = "surface_variant"\n'
                printf '        background_opacity = 0.88\n'
                printf '        background_radius = 12.0\n'
                printf '        center_password_text = false\n'
                printf '        input_opacity = 1.0\n'
                printf '        input_radius = 6.0\n'
                printf '        layout = "regular"\n'
                printf '        show_caps_lock = true\n'
                printf '        show_keyboard_layout = true\n'
                printf '        show_login_button = true\n'
                printf '        show_media = true\n'
                printf '        show_session_buttons = true\n'
                printf '        show_unlock_hint = true\n'
                printf '        show_weather = true\n\n'
            done
        else
            # ---------------- portable fallback -----------------------------
            # No live session: describe a single display-agnostic login box.
            # No `output` key means Noctalia applies it to every display.
            printf '[lockscreen_widgets]\n'
            printf 'enabled = true\n'
            printf 'schema_version = 2\n'
            printf 'widget_order = [ "lockscreen-login-box" ]\n\n'
            printf '    [lockscreen_widgets.grid]\n'
            printf '    cell_size = 16\n'
            printf '    major_interval = 4\n'
            printf '    visible = true\n\n'
            printf '    [lockscreen_widgets.widget."lockscreen-login-box"]\n'
            printf '    box_height = 196.0\n'
            printf '    box_width = 810.0\n'
            printf '    cx = 0.0\n'
            printf '    cy = 0.0\n'
            printf '    rotation = 0.0\n'
            printf '    type = "login_box"\n\n'
            printf '        [lockscreen_widgets.widget."lockscreen-login-box".settings]\n'
            printf '        background_color = "surface_variant"\n'
            printf '        background_opacity = 0.88\n'
            printf '        background_radius = 12.0\n'
            printf '        center_password_text = false\n'
            printf '        input_opacity = 1.0\n'
            printf '        input_radius = 6.0\n'
            printf '        layout = "regular"\n'
            printf '        show_caps_lock = true\n'
            printf '        show_keyboard_layout = true\n'
            printf '        show_login_button = true\n'
            printf '        show_media = true\n'
            printf '        show_session_buttons = true\n'
            printf '        show_unlock_hint = true\n'
            printf '        show_weather = true\n\n'
        fi
    } >"$tmp"

    if [ "$DRY_RUN" = 1 ]; then
        dry "generate ${dest/#$HOME/\$HOME}"
        sed 's/^/      | /' "$tmp"
        rm -f "$tmp"
        STATS_GENERATED=$((STATS_GENERATED + 1))
        return 0
    fi

    # Decide before backing up, so a no-op run produces no snapshot.
    if [ -f "$dest" ] && cmp -s "$tmp" "$dest" 2>/dev/null; then
        rm -f "$tmp"
        note "already current: ${dest/#$HOME/\$HOME}"
        _record_deployed "$dest"
        STATS_SKIPPED=$((STATS_SKIPPED + 1))
        return 0
    fi

    backup_file "$dest" 2>/dev/null || true
    mkdir -p "$(dirname "$dest")"
    local rc=0
    write_if_changed "$tmp" "$dest" || rc=$?
    case "$rc" in
        0) ok "generated ${dest/#$HOME/\$HOME}"
           STATS_GENERATED=$((STATS_GENERATED + 1))
           # Generated here, so owned here: uninstall.sh has to be able to
           # remove it, and it is not in deploy.manifest either.
           _record_deployed "$dest"
           record_written "$dest" ;;
        1) note "already current: ${dest/#$HOME/\$HOME}"
           _record_deployed "$dest"
           STATS_SKIPPED=$((STATS_SKIPPED + 1)) ;;
        2) warn "could not write $dest"; STATS_FAILED=$((STATS_FAILED + 1)); return 1 ;;
    esac
    return 0
}

# ---------------------------------------------------------------------------
# noctalia_apply_plugins — write [plugins] enabled = [...] for the chosen tier.
# Reads packages/plugins-core.txt / plugins-optional.txt and strips the
# "# Plugin ID  dep  reason" table down to bare plugin IDs.
# ---------------------------------------------------------------------------
noctalia_apply_plugins() {
    local dest="$HOME/.config/noctalia/config.toml"
    [ -f "$dest" ] || { warn "noctalia config.toml not deployed yet; skipping plugin list"; return 0; }

    local ids=() f line
    for f in "$DOTFILES_ROOT/packages/plugins-core.txt" \
             "$DOTFILES_ROOT/packages/plugins-optional.txt"; do
        [ -f "$f" ] || continue
        # The optional list is only read with the matching flag.
        case "$f" in
            *plugins-optional.txt)
                [ "${OPT_NOCTALIA_PLUGINS:-0}" = 1 ] && [ "${OPT_EXTRAS:-0}" = 1 ] || continue ;;
        esac

        while IFS= read -r line; do
            case "$line" in \#*|"") continue ;; esac
            # A line starting with whitespace is a CONTINUATION of the previous
            # row: these files are tables, and the "why it is core" prose wraps.
            # Taking its first field produced the literal plugin id "it", which
            # Noctalia then failed to load.
            case "$line" in [[:space:]]*) continue ;; esac
            # Skip the prose section at the bottom of the optional list.
            case "$line" in *"NEVER SHIPPED"*) break ;; esac
            line="$(printf '%s' "$line" | awk '{print $1}')"
            [ -n "$line" ] && ids+=("$line")
        done <"$f"
    done

    if [ "$DRY_RUN" = 1 ]; then
        dry "ensure [plugins] enabled lists ${#ids[@]} plugin(s) in ${dest/#$HOME/\$HOME}"
        return 0
    fi

    # CHECK, THEN REPAIR.
    #
    # This runs immediately after deploy_one has copied config.toml out of the
    # repository, and the repository's own [plugins] table already lists the six
    # core plugins. So on a default run the two steps want different bytes:
    # the copy restores the repo version, the rewrite re-applies, and the file
    # was rewritten on every single run — with an identical result. That made
    # "idempotent" false, and it triggered a Noctalia config reload each time.
    #
    # So: read what is deployed, and only touch the file if it is not already
    # the list we want. The rewrite then only actually happens when the tier
    # changed (e.g. --with-noctalia-plugins added the optional plugins).
    local want have
    want="$(printf '%s\n' "${ids[@]}" | sort)"
    have="$(awk '
        /^\[plugins\][[:space:]]*$/            { inplug = 1; next }
        inplug && /^\[/                         { inplug = 0 }
        inplug && /^[[:space:]]*enabled[[:space:]]*=/ { inarr = 1; next }
        inarr && /^\]/                          { inarr = 0; next }
        inarr { gsub(/^[[:space:]]*"|",?[[:space:]]*$/, ""); if ($0 != "") print }
    ' "$dest" | sort)"

    if [ "$want" = "$have" ]; then
        note "noctalia plugin list already correct (${#ids[@]} plugin(s))"
        return 0
    fi

    backup_file "$dest" 2>/dev/null || true
    local tmp block
    tmp="$(mktemp)"; block="$(mktemp)"

    # The replacement array is built into its own file and read back with
    # getline, rather than passed as a multi-line `awk -v` variable. That works
    # everywhere, whereas a newline inside -v is not portable between awk
    # implementations.
    {
        printf 'enabled = [\n'
        local i=0 last=$(( ${#ids[@]} - 1 ))
        for i in $(seq 0 "$last"); do
            if [ "$i" -eq "$last" ]; then
                printf '    "%s"\n' "${ids[$i]}"
            else
                printf '    "%s",\n' "${ids[$i]}"
            fi
        done
        printf ']\n'
    } >"$block"

    # Replace the ENTIRE [plugins] table, not just its first line.
    #
    # The previous version did `[plugins]` + getline + a new array, then tried
    # to skip the old one by pattern-matching `key = value` lines. The old array
    # is a list of quoted strings, not `key = value` lines, so they all survived
    # and got written back as orphaned TOML — a config that does not parse at
    # all, i.e. a desktop with no shell.
    #
    # A TOML table runs until the next table header, so dropping everything from
    # `[plugins]` up to the next `[` is exactly right and does not depend on the
    # shape of the value.
    awk -v blockfile="$block" '
        function emit(   line) {
            print "[plugins]"
            while ((getline line < blockfile) > 0) print line
            close(blockfile)
            inplug = 1; emitted = 1
        }
        !emitted && /^\[plugins\][[:space:]]*$/ { emit(); next }
        inplug && /^\[/                         { inplug = 0; print; next }
        inplug                                  { next }
        { print }

        # If [plugins] were the last table in the file, everything after it has
        # been dropped. Refuse to write that rather than produce a truncated
        # config; the caller falls back to leaving the file alone.
        END { if (inplug) exit 3 }
    ' "$dest" >"$tmp"
    rc=$?

    if [ "$rc" -eq 3 ]; then
        warn "[plugins] is the last table in $dest; refusing to rewrite it"
        note "the file would be truncated. Leaving the deployed config untouched."
        rm -f "$tmp" "$block"
        return 1
    fi

    if [ "$rc" -eq 0 ] && [ -s "$tmp" ]; then
        local wrc=0
        write_if_changed "$tmp" "$dest" || wrc=$?
        case "$wrc" in
            0) ok "noctalia plugins set (${#ids[@]}): ${ids[*]}" ;;
            1) note "noctalia plugin list already current (${#ids[@]} plugins)" ;;
            2) warn "could not write $dest"; return 1 ;;
        esac
    else
        warn "could not rewrite [plugins] in noctalia config (awk exit $rc); edit it manually"
    fi
    rm -f "$tmp" "$block"
    _record_deployed "$dest"
           record_written "$dest"
    return 0
}

# ---------------------------------------------------------------------------
# noctalia_verify [label]
#
# Must be zero warnings, not merely "valid". Anything noctalia complains about
# is either a dead widget or a typo, and both are worth catching before a
# login rather than after.
#
# In a dry run the deployed config is deliberately NOT updated, so validating it
# would report on yesterday's file. In that case the repository's own
# config.toml is validated instead, in a throwaway XDG_CONFIG_HOME, which is
# what would actually be installed. Plugin widget types only resolve when
# XDG_DATA_HOME and XDG_STATE_HOME point at real directories, so those are left
# alone.
# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
# noctalia_split_warnings <validate-output> <pending|real>
#
# `noctalia config validate` reports two kinds of warning that mean opposite
# things, and conflating them makes the installer and verify.sh disagree about
# whether the same machine is healthy.
#
#   "unrecognized widget type" for a PLUGIN-QUALIFIED name
#     ("noctalia/notes:notes") — the plugin's code has not been cloned yet.
#     Noctalia clones plugins itself on first run from the [plugins] list, so
#     this is expected before the first login and says nothing about the config.
#
#   everything else — an unknown setting, a bad scale, a dead widget — is a real
#   defect, and is exactly what this check is for.
#
# Only lines that ARE warnings are considered. validate also prints a summary
# line reading "Config is valid (3 warning(s))", and a loose match on "warn"
# counted that as a warning in its own right.
#
# Prints the matching lines, or nothing. Shared so there is one definition of
# "healthy" rather than one per caller.
# ---------------------------------------------------------------------------
noctalia_split_warnings() {
    local out="$1" which="$2"
    local warnline='^[[:space:]]*WARN[[:space:]]'
    local plugline='unrecognized widget type "[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+:'
    local w
    w="$(printf '%s\n' "$out" | grep -E "$warnline" || true)"
    case "$which" in
        pending) printf '%s\n' "$w" | grep -E "$plugline" || true ;;
        real)    printf '%s\n' "$w" | grep -vE "$plugline" || true ;;
        *)       return 1 ;;
    esac
    return 0
}

noctalia_verify() {
    local label="${1:-deployed config}"

    command -v noctalia >/dev/null 2>&1 || {
        warn "noctalia not installed; skipping config validation"
        return 0
    }

    local out rc tmp="" target
    if [ "$DRY_RUN" = 1 ]; then
        tmp="$(mktemp -d)"
        mkdir -p "$tmp/noctalia"
        cp "$DOTFILES_ROOT/config/noctalia/config.toml" "$tmp/noctalia/config.toml" || {
            rm -rf "$tmp"
            warn "could not stage config.toml for validation"
            return 1
        }
        target="$tmp"
    else
        target="$HOME/.config"
    fi

    # XDG_DATA_HOME and XDG_STATE_HOME are deliberately left pointing at the real
    # directories: plugin widget types only resolve when Noctalia can see the
    # plugins it has already cloned, and pointing them at a throwaway directory
    # manufactures warnings about widgets that are perfectly correct.
    out="$(XDG_CONFIG_HOME="$target" XDG_DATA_HOME="$HOME/.local/share" \
           XDG_STATE_HOME="$HOME/.local/state" noctalia config validate 2>&1)"
    rc=$?
    [ -n "$tmp" ] && rm -rf "$tmp"

    # Warnings are split into two classes, because they mean opposite things.
    #
    # "unrecognized widget type" for a PLUGIN-QUALIFIED name
    #   ("noctalia/notes:notes") means the plugin's code has not been cloned yet.
    #   Noctalia clones plugins itself on first run from the [plugins] list, so
    #   this is expected before the first login and says nothing about the config.
    #
    # Everything else — an unknown setting, a bad scale, a dead widget — is a real
    # defect in the config, and is exactly what this check is for.
    #
    # Only lines that ARE warnings are considered: `validate` also prints a
    # summary line reading "Config is valid (3 warning(s))", and matching that
    # loosely reported the count of warnings as a warning in its own right.
    local warnline='^[[:space:]]*WARN[[:space:]]'
    local plugline='unrecognized widget type "[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+:'
    local pending real_warns
    pending="$(noctalia_split_warnings "$out" pending)"
    real_warns="$(noctalia_split_warnings "$out" real)"

    if [ $rc -ne 0 ]; then
        err "noctalia config validate ($label): INVALID"
        printf '%s\n' "$out" | sed 's/^/        /'
        return 1
    fi

    if [ -n "$real_warns" ]; then
        warn "noctalia config validate ($label): $(printf '%s\n' "$real_warns" | grep -c .) real warning(s)"
        printf '%s\n' "$out" | sed 's/^/        /'
        return 1
    fi

    if [ -n "$pending" ]; then
        ok "noctalia config validate ($label): valid, no config warnings"
        note "$(printf '%s\n' "$pending" | grep -c .) plugin widget(s) not cloned yet."
        note "  Noctalia fetches them on first login, then re-run ./verify.sh."
        return 0
    fi

    ok "noctalia config validate ($label): clean"
    return 0
}
