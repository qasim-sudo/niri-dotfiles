#!/usr/bin/env bash
# lib/hardware.sh — hardware tier resolution + niri output.kdl generation.
#
# Two responsibilities:
#   1. hardware_resolve_tiers()  -> which packages/hardware/*.txt apply here
#   2. hardware_generate_output() -> write ~/.config/niri/cfg/output.kdl
#
# output.kdl is NEVER committed. It is regenerated on every install because the
# correct content is a property of the monitor attached right now, and it is
# wrong the moment you undock. A shipped version would hard-code a monitor name,
# a resolution and a refresh rate — all three machine-specific.

[ -n "${DOTFILES_HARDWARE_SH:-}" ] && return 0
DOTFILES_HARDWARE_SH=1

# ---------------------------------------------------------------------------
# Which hardware package tiers apply to this machine?
# Echoes one packages/hardware/<name>.txt filename per line.
# ---------------------------------------------------------------------------
hardware_resolve_tiers() {
    local tiers=()

    # --- Graphics: the Vulkan ICD that drives niri's blur + animation renderer
    case "$DETECT_GPU_VENDOR" in
        intel)   tiers+=("intel-graphics.txt") ;;
        amd)     tiers+=("amd-graphics.txt") ;;
        nouveau) tiers+=("nouveau-graphics.txt") ;;
        nvidia)
            if [ "${OPT_NVIDIA:-0}" = 1 ]; then
                tiers+=("nvidia-graphics.txt")
            else
                warn "NVIDIA GPU detected but not enabled. Re-run with --nvidia to install the proprietary driver, or install it yourself."
            fi
            ;;
        *)
            warn "no supported GPU detected; no Vulkan driver will be installed. niri blur will be unavailable."
            ;;
    esac

    # --- CPU microcode
    case "$DETECT_CPU_VENDOR" in
        GenuineIntel) tiers+=("intel-microcode.txt") ;;
        AuthenticAMD) tiers+=("amd-microcode.txt") ;;
    esac

    # --- SOF audio
    [ "$DETECT_HAS_SOF" = 1 ] && tiers+=("sof-audio.txt")

    # --- Laptop only
    [ "$DETECT_MACHINE_KIND" = "laptop" ] && tiers+=("laptop.txt")

    printf '%s\n' "${tiers[@]}"
}

# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
# Generate ~/.config/niri/cfg/output.kdl.
#
# The CONTENT is never committed — it is a description of the displays attached
# right now. A comment-only placeholder is committed instead, because
# config.kdl includes this path unconditionally and niri has no optional
# include, so the file has to exist for the config to load at all.
#
# Source of truth is DETECT_OUTPUT_DATA, built once by lib/detect.sh. If no
# niri session is live, no output block is written and niri auto-detects.
# ---------------------------------------------------------------------------
hardware_generate_output() {
    local dest="$HOME/.config/niri/cfg/output.kdl"
    local tmp; tmp="$(mktemp)"
    local n=0

    {
        printf '// GENERATED by the dotfiles installer. DO NOT EDIT, DO NOT COMMIT.\n'
        printf '// Rebuild at any time with:  ./regenerate.sh   (in the dotfiles repo)\n'
        printf '//\n'
        printf '// Describes the displays attached when this file was last generated.\n'
        printf '// Undocking or changing resolution/scale means regenerating it, or\n'
        printf '// deleting it so niri falls back to its own auto-detection.\n\n'

        if [ -n "$DETECT_OUTPUT_DATA" ]; then
            # The 7th column is the logical size; the trailing `_` discards it
            # rather than letting it stick to the last variable, which would emit
            # a transform of `normal<TAB>1920x1200`.
            local out mode scale x y tf _lsize
            while IFS=$'\t' read -r out mode scale x y tf _lsize; do
                [ -n "$out" ] || continue
                # niri wants the resolution only; the refresh rate belongs in a
                # "mode \"WxH@R\"" string, and a bare WxH means "preferred".
                printf 'output "%s" {\n' "$out"
                printf '    mode "%s"\n' "$mode"
                printf '    scale %s\n' "$scale"
                printf '    transform "%s"\n' "$tf"
                printf '    position x=%s y=%s\n' "$x" "$y"
                printf '}\n\n'
                n=$(( n + 1 ))
            done <<<"$DETECT_OUTPUT_DATA"
        fi

        if [ "$n" -eq 0 ]; then
            printf '// No display information was available when this was generated, so\n'
            printf '// there is deliberately no output block here. niri will auto-detect\n'
            printf '// your displays using its own EDID-based logic.\n'
            printf '//\n'
            printf '// To pin explicit modes, scale and positions, log into your niri\n'
            printf '// session and run:  ./regenerate.sh\n'
        fi
    } >"$tmp"

    if [ "$DRY_RUN" = 1 ]; then
        dry "generate $dest"
        cat "$tmp" | sed 's/^/      | /'
        rm -f "$tmp"
        STATS_GENERATED=$((STATS_GENERATED + 1))
        return 0
    fi

    # Decide before backing up: a generated file that is already correct must
    # not be copied into a new snapshot, or every run would produce one.
    if [ -f "$dest" ] && cmp -s "$tmp" "$dest" 2>/dev/null; then
        rm -f "$tmp"
        note "already current: $(printf '%s' "${dest/#$HOME/\$HOME}")"
        STATS_SKIPPED=$((STATS_SKIPPED + 1))
        return 0
    fi

    # Back up any existing generated file.
    if [ -e "$dest" ] && [ "$dest" != "$DOTFILES_ROOT/config/niri/cfg/output.kdl" ]; then
        backup_file "$dest" >/dev/null 2>&1 || true
    fi
    mkdir -p "$(dirname "$dest")"
    local rc=0
    write_if_changed "$tmp" "$dest" || rc=$?
    case "$rc" in
        0) ok "generated $(printf '%s' "${dest/#$HOME/\$HOME}")"
           STATS_GENERATED=$((STATS_GENERATED + 1))
           # The generated file is ours, so it is owned by this repository and
           # uninstall.sh must know to remove it. The committed placeholder is
           # never deployed, so this is the only thing that records the path.
           _record_deployed "$dest"
           record_written "$dest" ;;
        1) note "already current: $(printf '%s' "${dest/#$HOME/\$HOME}")"
           _record_deployed "$dest"
           STATS_SKIPPED=$((STATS_SKIPPED + 1)) ;;
        2) warn "could not write $dest"; STATS_FAILED=$((STATS_FAILED + 1)); return 1 ;;
    esac
    return 0
}
